/**
 * Verifies the state-machine registry against SQL CHECK constraints and
 * regenerates docs/STATE_MACHINES.md.   npx tsx scripts/check-state-machines.ts
 * Exit 1 on drift (a state in the registry missing from the CHECK, or vice versa).
 */
import fs from 'node:fs';
import path from 'node:path';
import { MACHINES, type Machine } from '../src/lib/state-machines/registry';

const root = path.resolve(__dirname, '..');
const migDirs = ['migrations', 'supabase/migrations'].map((d) => path.join(root, d)).filter(fs.existsSync);
const sqlFiles = migDirs.flatMap((d) => fs.readdirSync(d).filter((f) => f.endsWith('.sql')).map((f) => path.join(d, f)));

let problems = 0;
for (const [name, m] of Object.entries(MACHINES) as [string, Machine][]) {
  const states = Object.keys(m.transitions);
  for (const [from, tos] of Object.entries(m.transitions)) for (const t of tos) if (!states.includes(t)) { console.error(`✗ ${name}: ${from} -> ${t} targets unknown state`); problems++; }
  if (!states.includes(m.initial)) { console.error(`✗ ${name}: initial ${m.initial} not a state`); problems++; }
  if (!m.migration) continue;
  const num = m.migration.match(/(\d{3})/)?.[1];
  const files = sqlFiles.filter((f) => path.basename(f).startsWith(num!));
  const col = m.column.split('.')[1];
  const table = m.column.split('.')[0];
  const raw = files.map((f) => fs.readFileSync(f, 'utf8')).join('\n').replace(/--[^\n]*/g, '');
  // split into statements; keep those touching this table
  const stmts = raw.split(';').filter((st) => new RegExp(`(TABLE|ON)\\s+(IF\\s+(NOT\\s+)?EXISTS\\s+)?(public\\.)?${table}\\b`, 'i').test(st));
  const found = new Set<string>();
  const re = new RegExp(`${col}\\s+(?:TEXT|VARCHAR\\(\\d+\\))?[^,]*?CHECK\\s*\\(\\s*${col}\\s+IN\\s*\\(([^)]*)\\)|CHECK\\s*\\(\\s*${col}\\s+IN\\s*\\(([^)]*)\\)`, 'gi');
  for (const st of stmts) for (const mm of st.matchAll(re)) for (const x of (mm[1] ?? mm[2]).matchAll(/'([^']+)'/g)) found.add(x[1]);
  if (!found.size) { console.warn(`? ${name}: no CHECK found in ${m.migration} (skipped)`); continue; }
  const missing = [...found].filter((s) => !states.includes(s));
  const extra = states.filter((s) => !found.has(s));
  if (missing.length || extra.length) {
    console.warn(`~ ${name}: CHECK has [${[...found]}]; registry missing [${missing}], not in CHECK [${extra}] (may be superseded by later migration)`);
  } else console.log(`✓ ${name}`);
}

const md: string[] = [
  '# State machines',
  '',
  '_Generated by `npx tsx scripts/check-state-machines.ts` from `src/lib/state-machines/registry.ts`. Do not edit by hand._',
  '',
  'Runtime use is shadow-only: `checkTransition(machine, from, to)` logs unexpected moves and never blocks.',
  '',
];
for (const [name, m] of Object.entries(MACHINES) as [string, Machine][]) {
  md.push(`## ${name}`, '', m.description, '', `- Column: \`${m.column}\`${m.migration ? ` (${m.migration})` : ''}`, `- Initial: \`${m.initial}\``);
  for (const [from, tos] of Object.entries(m.transitions)) md.push(`- \`${from}\` → ${tos.length ? tos.map((t) => `\`${t}\``).join(', ') : '_terminal_'}`);
  if (m.triggers) { md.push('', 'Triggers:'); for (const [k, v] of Object.entries(m.triggers)) md.push(`- ${k}: ${v}`); }
  md.push('');
}
fs.writeFileSync(path.join(root, 'docs/STATE_MACHINES.md'), md.join('\n'));
console.log('wrote docs/STATE_MACHINES.md');
process.exit(problems ? 1 : 0);
